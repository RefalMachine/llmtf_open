def condition(expr, facts):
    if type(expr) is bool:
        return expr
    op, *args = expr
    if op == 'all': return all(condition(x, facts) for x in args)
    if op == 'any': return any(condition(x, facts) for x in args)
    if op == 'eq': return type(facts[args[0]]) is type(args[1]) and facts[args[0]] == args[1]
    if op == 'lt': return facts[args[0]] < args[1]
    raise ValueError(f'Unknown expression {expr}')


def worlds(card, facts):
    keys = [p['key'] for p in card['predicates']]
    if set(facts) != set(keys):
        raise ValueError('Fact keys differ from predicate schema')
    domains = []
    for p in card['predicates']:
        value = facts[p['key']]
        if value is not None and not any(type(value) is type(x) and value == x for x in p['domain']):
            raise ValueError('Fact outside finite domain')
        domains.append(p['domain'] if value is None else [value])
    return [dict(zip(keys, values)) for values in product(*domains)
            if all(condition(x, dict(zip(keys,values))) for x in card['constraints'])]


def oracle(card, facts):
    completed = worlds(card, facts)
    if not completed:
        raise ValueError('Inconsistent facts: no compatible worlds')
    traces = []
    for world in completed:
        branch = next((b for b in card['branches'] if condition(b['when'], world)), None)
        if branch is None:
            raise ValueError('Incomplete branch coverage')
        traces.append({'facts': world, 'branch': branch['id'], 'value': branch['value']})
    values = sorted({t['value'] for t in traces})
    return (values[0] if len(values) == 1 else UNKNOWN), traces

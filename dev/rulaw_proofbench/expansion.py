"""Candidate rules for the 300-case release; acceptance is a separate step.

This module does not modify the published pilot. Each predicate carries its
own wording for missing facts, so names never select legal semantics implicitly.
"""

from itertools import product

from .rules import AND, OR, OUTSIDE, boolean, card, eq, lt, number, pred


def flag(key, yes, no, missing, anchor):
    result = boolean(key, yes, no, anchor)
    result["unknown_phrase"] = missing
    return result


def choice(key, values, phrases, missing, anchor):
    result = pred(key, values, phrases, anchor)
    result["unknown_phrase"] = missing
    return result


def quantity(key, values, phrase, missing, anchor):
    result = number(key, values, phrase, anchor)
    result["unknown_phrase"] = missing
    return result


def binary_card(key, locator, scope, target, predicates, condition, cases,
                warning, dependencies=(), boundary_keys=(), constraints=()):
    return card(
        key, locator, scope, target + ' Ответьте «да» или «нет».', "none",
        predicates, [(condition, "да"), (True, "нет")], list(dependencies),
        warning, cases, boundary_keys, constraints,
    )


def boolean_cases(unknown_cases):
    return [list(values) for values in product((False, True), repeat=3)] + unknown_cases


